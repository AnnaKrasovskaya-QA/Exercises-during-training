# Вы — начинающий взломщик сейфа. На сейфе есть кнопочная панель с цифрами от 0 до 9. У сейфа есть секретный код — четырёхзначное число (от 1000 до 9999). Вам нужно его подобрать.
# Но сейф хитрый: после каждой попытки он сообщает только одну подсказку — сколько цифр в вашей догадке стоят на своём месте (то есть совпадают с секретным кодом и по значению, и по позиции).
# Например, если секретный код — 5274, а вы ввели 5299, то сейф ответит 2, потому что на своих местах стоят цифры 5 (первая) и 2 (вторая).
# Напишите программу, которая подбирает код за минимальное количество попыток, используя только циклы, условия и переменные (без строк и списков).
# Сам секретный код пусть пользователь вводит с клавиатуры при старте программы

password = 0
print('Введите 4-х значный секретный код от сейфа:')
n = int(input())
if 1000 <= n <= 9999:
    password = n
    print('Код принят')
else:
    print('Код должнем быть 4х значным в диапозоне от 1000 до 9999, код не сохранен')


if password > 0:
    b = password
    answer = 0

    for i in range(1, 5):
            print('Начало попытки №', i, 'сейчас совпадает - ', answer)
            for j in range(10):
                if j == b % 10:
                    answer += 1
                    b = b // 10
                elif b == 0:
                    break
            if b == 0:
                break
    print('Итого использовано попыток -', i, 'совпало - ', answer )
else:
    print('Нужно начать занаво')

